#include "dxvk_bridge.h"
#include <android/log.h>
#include <dlfcn.h>
#include <fstream>
#include <mutex>

#define LOG_TAG "VulkanCompatDXVK"
#define LOGI(...) __android_log_print(ANDROID_LOG_INFO, LOG_TAG, __VA_ARGS__)
#define LOGW(...) __android_log_print(ANDROID_LOG_WARN, LOG_TAG, __VA_ARGS__)

static std::mutex g_dxvk_mutex;
static PFN_dxvkAndroidSetWindow g_pfnSetWindow = nullptr;
static PFN_dxvkAndroidSetRenderSize g_pfnSetRenderSize = nullptr;
static PFN_dxvkAndroidGetWindowHandle g_pfnGetWindowHandle = nullptr;
static PFN_dxvkAndroidSetInstanceProcAddr g_pfnSetInstanceProcAddr = nullptr;
static ANativeWindow* g_current_window = nullptr;
static bool g_dxvk_resolved = false;

bool dxvk_bridge_init(void* dxvk_module_handle) {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    void* handle = dxvk_module_handle ? dxvk_module_handle : RTLD_DEFAULT;

    g_pfnSetWindow = (PFN_dxvkAndroidSetWindow)dlsym(handle, "dxvkAndroidSetWindow");
    g_pfnSetRenderSize = (PFN_dxvkAndroidSetRenderSize)dlsym(handle, "dxvkAndroidSetRenderSize");
    g_pfnGetWindowHandle = (PFN_dxvkAndroidGetWindowHandle)dlsym(handle, "dxvkAndroidGetWindowHandle");
    g_pfnSetInstanceProcAddr = (PFN_dxvkAndroidSetInstanceProcAddr)dlsym(handle, "dxvkAndroidSetInstanceProcAddr");

    if (!g_pfnSetWindow) {
        g_pfnSetWindow = (PFN_dxvkAndroidSetWindow)dlsym(RTLD_DEFAULT, "dxvkAndroidSetWindow");
    }
    if (!g_pfnSetRenderSize) {
        g_pfnSetRenderSize = (PFN_dxvkAndroidSetRenderSize)dlsym(RTLD_DEFAULT, "dxvkAndroidSetRenderSize");
    }
    if (!g_pfnGetWindowHandle) {
        g_pfnGetWindowHandle = (PFN_dxvkAndroidGetWindowHandle)dlsym(RTLD_DEFAULT, "dxvkAndroidGetWindowHandle");
    }
    if (!g_pfnSetInstanceProcAddr) {
        g_pfnSetInstanceProcAddr = (PFN_dxvkAndroidSetInstanceProcAddr)dlsym(RTLD_DEFAULT, "dxvkAndroidSetInstanceProcAddr");
    }

    g_dxvk_resolved = (g_pfnSetWindow != nullptr);

    LOGI("DXVK bridge status: %s (SetWindow=%p, SetRenderSize=%p, GetWindow=%p, SetInstanceProcAddr=%p)",
         g_dxvk_resolved ? "RESOLVED" : "NOT_FOUND_USING_FALLBACK",
         (void*)g_pfnSetWindow, (void*)g_pfnSetRenderSize,
         (void*)g_pfnGetWindowHandle, (void*)g_pfnSetInstanceProcAddr);

    if (g_pfnSetWindow && g_current_window) {
        g_pfnSetWindow(g_current_window);
    }

    return g_dxvk_resolved;
}

void dxvk_bridge_set_window(ANativeWindow* window) {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    g_current_window = window;
    if (g_pfnSetWindow) {
        LOGI("Forwarding ANativeWindow=%p to dxvkAndroidSetWindow", window);
        g_pfnSetWindow(window);
    } else {
        LOGW("dxvkAndroidSetWindow not resolved yet, cached window=%p", window);
    }
}

void dxvk_bridge_set_render_size(uint32_t width, uint32_t height) {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    if (g_pfnSetRenderSize) {
        LOGI("Setting DXVK internal render size to %ux%u", width, height);
        g_pfnSetRenderSize(width, height);
    }
}

ANativeWindow* dxvk_bridge_get_window_handle() {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    if (g_pfnGetWindowHandle) {
        return g_pfnGetWindowHandle();
    }
    return g_current_window;
}

void dxvk_bridge_set_instance_proc_addr(void* pfn) {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    if (g_pfnSetInstanceProcAddr) {
        g_pfnSetInstanceProcAddr(pfn);
    }
}

bool dxvk_bridge_write_config(
    const std::string& game_dir,
    int fps_limit,
    bool enable_pipeline_cache,
    bool widescreen_fix,
    bool cpu_textures,
    bool triple_buffering
) {
    if (game_dir.empty()) return false;

    std::string config_path = game_dir + "/dxvk.conf";
    std::ofstream out(config_path);
    if (!out.is_open()) {
        LOGW("Unable to write dxvk.conf at %s", config_path.c_str());
        return false;
    }

    out << "# Generated by VulkanCompatShell\n";
    out << "[dxvk]\n";
    out << "dxvk.enableGraphicsPipelineLibrary = True\n";
    out << "dxvk.numCompilerThreads = 4\n";

    if (enable_pipeline_cache) {
        out << "dxvk.pipelineCache = True\n";
        out << "dxvk.cachePath = " << game_dir << "\n";
        out << "dxvk.cacheFile = vulkan_pipelines.bin\n";
    } else {
        out << "dxvk.pipelineCache = False\n";
    }

    out << "\n[d3d9]\n";
    if (fps_limit > 0) {
        out << "d3d9.maxFrameRate = " << fps_limit << "\n";
    } else {
        out << "d3d9.maxFrameRate = 0\n";
    }

    out << "d3d9.deferSurfaceCreation = True\n";
    out << "d3d9.dpiAware = False\n";
    out << "d3d9.customVendorId = 10de\n"; // NVIDIA vendor ID spoof for standard DX9 compat
    out << "d3d9.hasManagedTextures = " << (cpu_textures ? "True" : "False") << "\n";
    out << "d3d9.presentInterval = " << (triple_buffering ? "0" : "1") << "\n";
    out << "d3d9.tearFree = False\n";

    if (widescreen_fix) {
        out << "d3d9.lenientClear = True\n";
        out << "d3d9.supportAspectRatios = True\n";
    }

    out.close();
    LOGI("dxvk.conf written successfully to %s", config_path.c_str());
    return true;
}

bool dxvk_bridge_is_active() {
    std::lock_guard<std::mutex> lock(g_dxvk_mutex);
    return g_dxvk_resolved;
}
